# Unicode 17.0.0 / UAX #29 revision47. Offline, pinned original inputs.
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
Set-StrictMode -Version Latest
$unit=Split-Path -Parent $PSScriptRoot
$source=Join-Path $unit 'ThirdParty/Unicode17'
$manifest=Get-Content -Raw -LiteralPath (Join-Path $source 'Sources.json')|ConvertFrom-Json -AsHashtable
if($manifest.unicode_version -cne '17.0.0' -or $manifest.uax29_revision -ne 47){throw 'Unexpected Unicode contract'}
foreach($name in $manifest.files.Keys){
 if((Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $source $name)).Hash.ToLowerInvariant() -cne $manifest.files[$name].sha256){throw "Pinned Unicode input changed: $name"}
}
function Read-Ranges([string]$Name,[string]$Kind){
 $items=[Collections.Generic.List[object]]::new()
 foreach($line in [IO.File]::ReadLines((Join-Path $source $Name))){
  $body=($line.Split('#')[0]).Trim()
  if(-not $body){continue}
  $parts=$body.Split(';')|ForEach-Object {$_.Trim()}
  if($Kind -ceq 'incb'){
   if($parts.Count -lt 3 -or $parts[1] -cne 'InCB'){continue};$property=$parts[2]
  }elseif($Kind -ceq 'ep'){
   if($parts[1] -cne 'Extended_Pictographic'){continue};$property='yes'
  }else{$property=$parts[1]}
  $bounds=$parts[0].Split('..',[StringSplitOptions]::None)
  $first=[Convert]::ToUInt32($bounds[0],16);$last=$first
  if($bounds.Count -eq 2){$last=[Convert]::ToUInt32($bounds[1],16)}
  if($first -gt $last -or $last -gt 0x10ffff){throw 'Invalid property range'}
  # Hangul LV/LVT is classified arithmetically, including every syllable.
  if($Kind -ceq 'gcb' -and $first -ge 0xac00 -and $last -le 0xd7a3){continue}
  $items.Add(@{first=$first;last=$last;property=$property})
 }
 $sorted=@($items|Sort-Object {$_.first})
 $previous=-1
 foreach($item in $sorted){if($item.first -le $previous){throw 'Overlapping property ranges'};$previous=$item.last}
 return ,$sorted
}
$gcb=Read-Ranges 'GraphemeBreakProperty.txt' 'gcb'
$incb=Read-Ranges 'DerivedCoreProperties.txt' 'incb'
$ep=Read-Ranges 'emoji-data.txt' 'ep'
$out=[Text.StringBuilder]::new()
[void]$out.AppendLine('// Generated by Tools/Generate-Grapheme.ps1. Unicode17.0.0, UAX29rev47.')
[void]$out.AppendLine('// Pinned original data and Unicode license: ../../ThirdParty/Unicode17/.')
[void]$out.AppendLine('pub const Gcb = enum(u4) { Other, CR, LF, Control, Extend, ZWJ, Regional_Indicator, Prepend, SpacingMark, L, V, T, LV, LVT };')
[void]$out.AppendLine('pub const Incb = enum(u2) { None, Consonant, Extend, Linker };')
[void]$out.AppendLine('const GRange = struct { first: u21, last: u21, value: Gcb };')
[void]$out.AppendLine('const IRange = struct { first: u21, last: u21, value: Incb };')
[void]$out.AppendLine('const Range = struct { first: u21, last: u21 };')
foreach($table in @(@('gcb_ranges','GRange',$gcb),@('incb_ranges','IRange',$incb),@('ep_ranges','Range',$ep))){
 [void]$out.AppendLine(('const {0} = [_]{1}{{' -f $table[0],$table[1]))
 foreach($entry in $table[2]){
  $value=if($table[1] -ceq 'Range'){''}else{', .value = .'+$entry.property}
  [void]$out.AppendLine(('    .{{ .first = 0x{0:x}, .last = 0x{1:x}{2} }},' -f $entry.first,$entry.last,$value))
 }
 [void]$out.AppendLine('};')
}
[void]$out.Append(@'
fn lookup(comptime T: type, ranges: []const T, scalar: u21) ?T {
    var low: usize = 0;
    var high: usize = ranges.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        const range = ranges[middle];
        if (scalar < range.first) { high = middle; } else if (scalar > range.last) { low = middle + 1; } else return range;
    }
    return null;
}
pub fn gcb(scalar: u21) Gcb {
    if (scalar >= 0x20 and scalar < 0x7f) return .Other;
    if (scalar >= 0xac00 and scalar <= 0xd7a3) return if ((scalar - 0xac00) % 28 == 0) .LV else .LVT;
    return if (lookup(GRange, &gcb_ranges, scalar)) |r| r.value else .Other;
}
pub fn incb(scalar: u21) Incb {
    if (scalar < 0x300) return .None;
    return if (lookup(IRange, &incb_ranges, scalar)) |r| r.value else .None;
}
pub fn extendedPictographic(scalar: u21) bool {
    if (scalar < 0xa9) return false;
    return lookup(Range, &ep_ranges, scalar) != null;
}
'@)
$utf8=[Text.UTF8Encoding]::new($false)
[IO.File]::WriteAllText((Join-Path $unit 'Bindings/Zig/grapheme_properties.zig'),$out.ToString().Replace("`r`n","`n").TrimEnd()+"`n",$utf8)
$destination=Join-Path $unit 'Bindings/Zig/Data'
[void][IO.Directory]::CreateDirectory($destination)
[IO.File]::WriteAllBytes((Join-Path $destination 'GraphemeBreakTest.txt'),[IO.File]::ReadAllBytes((Join-Path $source 'GraphemeBreakTest.txt')))
Write-Output ('Generated Unicode17: GCB={0}, InCB={1}, EP={2}' -f $gcb.Count,$incb.Count,$ep.Count)
